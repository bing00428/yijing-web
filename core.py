def calc_men_zhu_zao(door_dir: str, main_dir: str, kitchen_dir: str) -> dict:
    """
    阳宅三要：门主灶分析
    来源: 《阳宅三要》· 赵九峰
    "门乃进出之路，主乃居之所，灶乃食之方。"
    "只要门主相生，即以吉断，相克即以凶断。"
    "第一与门相生，其次与主相生。须要门主灶三者，各得其所。"

    Args:
        door_dir: 大门方位（北/南/东/西/东北/东南/西南/西北）
        main_dir: 主房方位
        kitchen_dir: 厨房方位
    Returns:
        dict: {门主关系, 门灶关系, 主灶关系, 总评}
    """
    door_gua = lookup_trigram_by_dir(door_dir)
    main_gua = lookup_trigram_by_dir(main_dir)
    kitchen_gua = lookup_trigram_by_dir(kitchen_dir)

    door_wx = TRIGRAMS.get(door_gua, {}).get("element", "未知")
    main_wx = TRIGRAMS.get(main_gua, {}).get("element", "未知")
    kitchen_wx = TRIGRAMS.get(kitchen_gua, {}).get("element", "未知")

    # 门主关系
    if door_wx == main_wx:
        men_zhu_rel = "比和"
        men_zhu_jx = "吉"
        men_zhu_detail = f"门({door_gua}·{door_wx})与主({main_gua}·{main_wx})五行相同，比和为吉，家道和睦。"
    elif _wu_xing_sheng(door_wx, main_wx):
        men_zhu_rel = "门生主"
        men_zhu_jx = "吉"
        men_zhu_detail = f"门({door_gua}·{door_wx})生主({main_gua}·{main_wx})，门来生主，大吉，主家运亨通。"
    elif _wu_xing_sheng(main_wx, door_wx):
        men_zhu_rel = "主生门"
        men_zhu_jx = "平"
        men_zhu_detail = f"主({main_gua}·{main_wx})生门({door_gua}·{door_wx})，主去生门，泄气，平。"
    elif _wu_xing_ke(door_wx, main_wx):
        men_zhu_rel = "门克主"
        men_zhu_jx = "凶"
        men_zhu_detail = f"门({door_gua}·{door_wx})克主({main_gua}·{main_wx})，门来克主，凶，主家运受阻。"
    elif _wu_xing_ke(main_wx, door_wx):
        men_zhu_rel = "主克门"
        men_zhu_jx = "次凶"
        men_zhu_detail = f"主({main_gua}·{main_wx})克门({door_gua}·{door_wx})，主克门，犹我胜彼，次凶。"
    else:
        men_zhu_rel = "未知"
        men_zhu_jx = "平"
        men_zhu_detail = "门主五行关系不明。"

    # 门灶关系
    if door_wx == kitchen_wx:
        men_zao_rel = "比和"
        men_zao_jx = "吉"
        men_zao_detail = f"门({door_gua}·{door_wx})与灶({kitchen_gua}·{kitchen_wx})比和，吉。"
    elif _wu_xing_sheng(door_wx, kitchen_wx):
        men_zao_rel = "门生灶"
        men_zao_jx = "平"
        men_zao_detail = f"门({door_gua}·{door_wx})生灶({kitchen_gua}·{kitchen_wx})，门来生灶，平。"
    elif _wu_xing_sheng(kitchen_wx, door_wx):
        men_zao_rel = "灶生门"
        men_zao_jx = "吉"
        men_zao_detail = f"灶({kitchen_gua}·{kitchen_wx})生门({door_gua}·{door_wx})，灶来生门，吉。"
    elif _wu_xing_ke(door_wx, kitchen_wx):
        men_zao_rel = "门克灶"
        men_zao_jx = "次凶"
        men_zao_detail = f"门({door_gua}·{door_wx})克灶({kitchen_gua}·{kitchen_wx})，门克灶，次凶。"
    elif _wu_xing_ke(kitchen_wx, door_wx):
        men_zao_rel = "灶克门"
        men_zao_jx = "凶"
        men_zao_detail = f"灶({kitchen_gua}·{kitchen_wx})克门({door_gua}·{door_wx})，灶来克门，凶。"
    else:
        men_zao_rel = "未知"
        men_zao_jx = "平"
        men_zao_detail = "门灶五行关系不明。"

    # 主灶关系
    if main_wx == kitchen_wx:
        zhu_zao_rel = "比和"
        zhu_zao_jx = "吉"
        zhu_zao_detail = f"主({main_gua}·{main_wx})与灶({kitchen_gua}·{kitchen_wx})比和，吉。"
    elif _wu_xing_sheng(main_wx, kitchen_wx):
        zhu_zao_rel = "主生灶"
        zhu_zao_jx = "平"
        zhu_zao_detail = f"主({main_gua}·{main_wx})生灶({kitchen_gua}·{kitchen_wx})，主去生灶，平。"
    elif _wu_xing_sheng(kitchen_wx, main_wx):
        zhu_zao_rel = "灶生主"
        zhu_zao_jx = "吉"
        zhu_zao_detail = f"灶({kitchen_gua}·{kitchen_wx})生主({main_gua}·{main_wx})，灶来生主，吉。"
    elif _wu_xing_ke(main_wx, kitchen_wx):
        zhu_zao_rel = "主克灶"
        zhu_zao_jx = "次凶"
        zhu_zao_detail = f"主({main_gua}·{main_wx})克灶({kitchen_gua}·{kitchen_wx})，主克灶，次凶。"
    elif _wu_xing_ke(kitchen_wx, main_wx):
        zhu_zao_rel = "灶克主"
        zhu_zao_jx = "凶"
        zhu_zao_detail = f"灶({kitchen_gua}·{kitchen_wx})克主({main_gua}·{main_wx})，灶来克主，凶。"
    else:
        zhu_zao_rel = "未知"
        zhu_zao_jx = "平"
        zhu_zao_detail = "主灶五行关系不明。"

    # 总评
    ji_count = sum(1 for jx in [men_zhu_jx, men_zao_jx, zhu_zao_jx] if jx == "吉")
    xiong_count = sum(1 for jx in [men_zhu_jx, men_zao_jx, zhu_zao_jx] if jx in ("凶", "次凶"))

    if ji_count >= 2 and xiong_count == 0:
        zong_ping = "上吉"
        zong_ping_detail = "门主灶三者相生或比和，各得其所。门生主、主生灶、灶生门，循环相生，人丁大旺，福寿双全。"
    elif ji_count >= 1 and xiong_count <= 1:
        zong_ping = "中平"
        zong_ping_detail = "门主灶有吉有平，整体尚可。宜调整灶位或门向，使三者相生。"
    else:
        zong_ping = "凶"
        zong_ping_detail = "门主灶相克较多，门主不相生。宜调整门、主、灶位置，使之五行相生。"

    return {
        "门": f"{door_gua}({door_dir}·{door_wx})", "主": f"{main_gua}({main_dir}·{main_wx})",
        "灶": f"{kitchen_gua}({kitchen_dir}·{kitchen_wx})",
        "门主": {"关系": men_zhu_rel, "吉凶": men_zhu_jx, "详解": men_zhu_detail},
        "门灶": {"关系": men_zao_rel, "吉凶": men_zao_jx, "详解": men_zao_detail},
        "主灶": {"关系": zhu_zao_rel, "吉凶": zhu_zao_jx, "详解": zhu_zao_detail},
        "总评": {"吉凶": zong_ping, "详解": zong_ping_detail},
    }


