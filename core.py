def yarrow_stalk() -> list[int]:
    """
    大衍之数蓍草起卦（《系辞上传》第九章）
    大衍之数五十，其用四十有九。
    分二、挂一、揲四、归奇，三变成一爻，十八变成六爻。
    
    Returns:
        6爻列表 (6/7/8/9)
    """
    yao_values = []
    for _ in range(6):  # 六爻
        remainder = 49  # 其用四十有九
        for _ in range(3):  # 三变
            # 分二
            left = random.randint(1, remainder - 1)
            right = remainder - left
            # 挂一
            right -= 1
            # 揲四（分两边各除以4）
            left_mod = left % 4
            if left_mod == 0:
                left_mod = 4
            right_mod = right % 4
            if right_mod == 0:
                right_mod = 4
            # 归奇 — 从总杆数中减去小余数
            remainder -= (left_mod + right_mod + 1)
        # 三变后得到爻值（49根起，三变后剩36/37/38/39，除以4得6/7/8/9）
        yao = remainder // 4
        if yao == 9:
            yao_values.append(6)  # 老阴
        elif yao == 8:
            yao_values.append(7)  # 少阳
        elif yao == 7:
            yao_values.append(8)  # 少阴
        else:
            yao_values.append(9)  # 老阳
    return yao_values


