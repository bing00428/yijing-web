def toss_coins(n: int = 6) -> list[int]:
    """
    铜钱法起卦（京房六爻法）
    每次抛3枚铜钱，结果记为：
      - 3字(乾): 老阳(9) -- X--  动爻
      - 3背(坤): 老阴(6) -- -- X  动爻
      - 2字1背(少阳): 7        静爻
      - 2背1字(少阴): 8        静爻
    自下而上记录6次，得到6爻卦
    
    Returns:
        (爻列, 动爻列表) - 爻列每元素为 6/7/8/9
    """
    yao_values = []
    moving_lines = []
    for i in range(6):
        coins = [random.choice([0, 1]) for _ in range(3)]
        total = sum(coins)  # 0=背, 1=字
        if total == 0:
            val = 9  # 老阳
            moving_lines.append(i + 1)
        elif total == 1:
            val = 8  # 少阴
        elif total == 2:
            val = 7  # 少阳
        else:
            val = 6  # 老阴
            moving_lines.append(i + 1)
        yao_values.append(val)
    return yao_values, moving_lines


