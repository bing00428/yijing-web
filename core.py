def xing_relationship(elem1: str, elem2: str) -> str:
    """判断五行关系: 相生, 相克, 比和(相同), 泄(我生), 耗(克我)"""
    if elem1 == elem2:
        return "比和"
    if XING相生.get(elem1) == elem2:
        return "相生"  # elem1生elem2
    if XING相克.get(elem1) == elem2:
        return "相克"  # elem1克elem2
    if XING相生.get(elem2) == elem1:
        return "泄"  # elem2生elem1，即elem1被泄
    if XING相克.get(elem2) == elem1:
        return "耗"  # elem2克elem1，即elem1被耗
    return "未知"


