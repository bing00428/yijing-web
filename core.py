def _lua_qin_from(wuxing_me: str, wuxing_ta: str) -> str:
    """根据五行关系计算六亲（me=我=卦五行, ta=他=地支五行）"""
    if wuxing_me == wuxing_ta:
        return "兄弟"  # 同我者为兄弟
    if XING相生.get(wuxing_me) == wuxing_ta:
        return "子孙"  # 我生者为子孙
    # 生我者为父母
    _rev_sheng = {v: k for k, v in XING相生.items()}
    if _rev_sheng.get(wuxing_me) == wuxing_ta:
        return "父母"
    if XING相克.get(wuxing_me) == wuxing_ta:
        return "妻财"  # 我克者为妻财
    # 克我者为官鬼
    _rev_ke = {v: k for k, v in XING相克.items()}
    if _rev_ke.get(wuxing_me) == wuxing_ta:
        return "官鬼"
    return "？"


