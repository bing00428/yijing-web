# 星宫生克判定规则
# 来源: 《八宅明镜》· 星宫生克
#   "宫克星也。宫为主，星为客，主可胜客，客不可欺主也。"
#   星生宫: 吉（星来生宫，吉星愈吉）
#   宫克星: 吉（宫克星，主胜客，吉）
#   星克宫: 凶（星来克宫，吉者不吉，凶者愈凶）
#   宫生星: 吉（宫来生星，助星之力）
#   星宫比和: 吉（同五行，相互扶助）
#   注: 与其星克宫，不如宫克星。宫克星吉，星克宫凶。
def calc_xing_gong_sheng_ke(star: str, palace_gua: str) -> dict:
    """
    计算星宫生克关系
    来源: 《八宅明镜》· 星宫生克
    Args:
        star: 星名（生气/天医/延年中/伏位/六煞/五鬼/绝命/祸害）
        palace_gua: 宫位卦名（乾/坎/艮/震/巽/离/坤/兑）
    Returns:
        dict: {关系, 吉凶, 详解}
    """
    star_wx = JIU_XING_WU_XING.get(JIU_XING_MAPPING.get(star, star), "未知")
    palace_wx = TRIGRAMS.get(palace_gua, {}).get("element", "未知")

    if star_wx == palace_wx:
        relation = "比和"
        ji_xiong = "吉"
        detail = f"星{star}({star_wx})与宫{palace_gua}({palace_wx})五行相同，相互扶助，吉。"
    elif _wu_xing_sheng(star_wx, palace_wx):
        # 星生宫
        relation = "星生宫"
        ji_xiong = "吉"
        detail = f"星{star}({star_wx})生宫{palace_gua}({palace_wx})，吉星来生，吉上加吉。"
    elif _wu_xing_ke(star_wx, palace_wx):
        # 星克宫
        relation = "星克宫"
        ji_xiong = "凶"
        detail = f"星{star}({star_wx})克宫{palace_gua}({palace_wx})，客欺主，吉者不吉，凶者愈凶。"
    elif _wu_xing_ke(palace_wx, star_wx):
        # 宫克星
        relation = "宫克星"
        ji_xiong = "吉"
        detail = f"宫{palace_gua}({palace_wx})克星{star}({star_wx})，主胜客，恶人效顺，不甚作祸。"
    elif _wu_xing_sheng(palace_wx, star_wx):
        # 宫生星
        relation = "宫生星"
        ji_xiong = "吉"
        detail = f"宫{palace_gua}({palace_wx})生星{star}({star_wx})，宫来助星，吉。"
    else:
        relation = "未知"
        ji_xiong = "平"
        detail = f"星{star}({star_wx})与宫{palace_gua}({palace_wx})关系不明。"

    return {"星": star, "宫": palace_gua, "星五行": star_wx, "宫五行": palace_wx, "关系": relation, "吉凶": ji_xiong, "详解": detail}


