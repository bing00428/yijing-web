def get_gan_zhi(year: int) -> tuple[str, str]:
    """
    根据公历年份计算天干地支（以立春为界简化处理，以年份为准）
    来源: 《隋书·律历志》干支纪年法
    
    算法:
    - 天干 = (年份 - 3) % 10，对应 TIAN_GAN
    - 地支 = (年份 - 3) % 12，对应 DI_ZHI
    
    Args:
        year: 公历年份
        
    Returns:
        (天干, 地支) 元组
    """
    # 公元4年为甲子年，以此为基准
    tg_idx = (year - 4) % 10
    dz_idx = (year - 4) % 12
    return TIAN_GAN[tg_idx], DI_ZHI[dz_idx]


