def check_house_shape(house_shape: str) -> dict:
    """
    根据房屋形状判断缺角凸角情况
    Args:
        house_shape: 房屋形状描述（如"L型"、"缺西北"、"东南凸角"等）
    Returns:
        dict: 形状分析结果
    """
    result = {
        "房屋形状": house_shape,
        "缺角情况": [],
        "凸角情况": [],
        "整体评价": "",
    }
    
    # 简单判断逻辑
    if "缺" in house_shape:
        for area in BA_GUA_LEI_XIANG.keys():
            if area in house_shape:
                result["缺角情况"].append(area)
    
    if "凸" in house_shape:
        for area in BA_GUA_LEI_XIANG.keys():
            if area in house_shape:
                result["凸角情况"].append(area)
    
    # 整体评价
    if not result["缺角情况"] and not result["凸角情况"]:
        result["整体评价"] = "户型方正，气运稳定。"
    else:
        # 根据鲁班经宅形判断
        zhai_xing = LU_BAN_JING_ZHAI_XING.get("缺角宅", "")
        result["宅形判定"] = zhai_xing
        
        # 严重程度评估
        qiang_count = len(result["缺角情况"])
        tu_count = len(result["凸角情况"])
        
        if qiang_count == 0 and tu_count == 0:
            result["严重程度"] = "无"
        elif qiang_count <= 1 and tu_count <= 1:
            result["严重程度"] = QUE_JIANG_YAN_ZHONG_DU.get("轻微", {}).get("标准", "轻微")
            result["建议"] = QUE_JIANG_YAN_ZHONG_DU.get("轻微", {}).get("建议", "可适当化解，不必过度紧张")
        elif qiang_count <= 2:
            result["严重程度"] = QUE_JIANG_YAN_ZHONG_DU.get("中等", {}).get("标准", "中等")
            result["建议"] = QUE_JIANG_YAN_ZHONG_DU.get("中等", {}).get("建议", "建议进行风水调理")
        elif qiang_count <= 4:
            result["严重程度"] = QUE_JIANG_YAN_ZHONG_DU.get("严重", {}).get("标准", "严重")
            result["建议"] = QUE_JIANG_YAN_ZHONG_DU.get("严重", {}).get("建议", "应尽快进行风水调理")
        else:
            result["严重程度"] = QUE_JIANG_YAN_ZHONG_DU.get("极严重", {}).get("标准", "极严重")
            result["建议"] = QUE_JIANG_YAN_ZHONG_DU.get("极严重", {}).get("建议", "需全面调理，必要时考虑搬家")
        
        # 五行分布分析
        wu_xing_count = {"金": 0, "木": 0, "水": 0, "火": 0, "土": 0}
        for area in result["缺角情况"]:
            if area in BA_GUA_LEI_XIANG:
                wx = BA_GUA_LEI_XIANG[area].get("五行", "")
                if wx in wu_xing_count:
                    wu_xing_count[wx] += 1
        
        # 找出缺失最多的五行
        max_wx = max(wu_xing_count, key=wu_xing_count.get) if any(wu_xing_count.values()) else ""
        if max_wx:
            result["五行缺失"] = {
                "缺失最多": f"{max_wx}（{wu_xing_count[max_wx]}个方位）",
                "各方位统计": wu_xing_count,
                "建议": f"整体气场中{max_wx}气偏弱，可针对性补充",
            }
    
    return result
