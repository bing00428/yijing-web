def calc_benming_wuxing_strength(year: int, month: int = 0, day: int = 0, hour: int = 12) -> dict:
    """
    根据四柱八字分析五行强弱
    统计四柱中天干地支的五行，计算金木水火土各元素得分
    
    Args:
        year: 公历年
        month: 月
        day: 日
        hour: 时辰索引对应的小时
    
    Returns:
        dict: 包含各五行得分、排名、强弱分析
    """
    from calendar import monthrange
    
    # 获取年柱干支
