def _get_jie_date(year: int, jie_idx: int) -> tuple[int, int]:
    """
    根据查找表获取节气日期
    
    若查找表中无该年数据，使用最近的基准年 + timedelta 推算
    jie_idx: 0=立春, 1=惊蛰, ..., 11=小寒
    返回 (月, 日)
    """
    import datetime
    
    if year in JIE_QI_TABLE:
        return JIE_QI_TABLE[year][JIE_QI_NAMES[jie_idx]]
    
    # 查找最近的基准年
    closest_year = min(JIE_QI_TABLE.keys(), key=lambda y: abs(y - year))
    base_dates = JIE_QI_TABLE[closest_year]
    
    base_li_chun = datetime.date(closest_year,
                                  base_dates["立春"][0],
                                  base_dates["立春"][1])
    base_jie = datetime.date(closest_year,
                              base_dates[JIE_QI_NAMES[jie_idx]][0],
                              base_dates[JIE_QI_NAMES[jie_idx]][1])
    delta = (base_jie - base_li_chun).days
    
    # 目标年立春日期（近似：取年号%4的偏移）
    li_chun_offsets = {0: -1, 1: 0, 2: 1, 3: 0}  # 年号%4 -> 立春偏移
    offset = li_chun_offsets.get(year % 4, 0)
    try:
        target_li_chun = datetime.date(year, base_li_chun.month, max(1, base_li_chun.day + offset))
        target_jie = target_li_chun + datetime.timedelta(days=delta)
        return (target_jie.month, target_jie.day)
    except Exception:
        return base_dates[JIE_QI_NAMES[jie_idx]]


def _day_of_year(year: int, month: int, day: int) -> int:
    """计算公历日期在一年中的第几天"""
    import datetime
    return datetime.date(year, month, day).timetuple().tm_yday


def get_gan_zhi_month(year: int, month: int, day: int) -> str:
    """
    根据公历日期计算月柱干支
    来源: 《渊海子平》、《三命通会》
    
    八字月份以"节"为界（非农历或公历月份）：
    - 立春 → 寅月 (正月)
    - 惊蛰 → 卯月 (二月)
    - ...
    - 小寒 → 丑月 (十二月)
    
    月干由年干通过五虎遁诀推算。
    
    Args:
        year: 公历年份
        month: 公历月
        day: 公历日
        
    Returns:
        月柱干支，如"戊寅"
    """
    import datetime
    
    target_doy = _day_of_year(year, month, day)
    
    # 先判断是否在立春之前（立春前用上一年的年干）
    li_chun_m, li_chun_d = _get_jie_date(year, 0)
    li_chun_doy = _day_of_year(year, li_chun_m, li_chun_d)
    
    if target_doy < li_chun_doy:
        # 立春前：使用上一年的年干
        check_year = year - 1
    else:
        check_year = year
    
    year_gan, _ = get_gan_zhi(check_year)
    yue_gan_offset = YUE_GAN_OFFSET.get(year_gan, 2)
    
    # 遍历十二节，找到目标日期落在哪个节气之后
    current_zhi_idx = 11  # 默认小寒后为丑月（索引11）
    for i in range(12):
        jie_month, jie_day = _get_jie_date(year, i)
        jie_doy = _day_of_year(year, jie_month, jie_day)
        if target_doy >= jie_doy:
            current_zhi_idx = i
        else:
            break
    
    # 计算月干
    yue_gan_idx = (yue_gan_offset + current_zhi_idx) % 10
    yue_zhi = JIE_TO_ZHI[current_zhi_idx]
    return f"{TIAN_GAN[yue_gan_idx]}{yue_zhi}"


def get_mingben_wuxing(year: int, month: int = 0, day: int = 0, hour: int = 12) -> dict:
    """
    本命五行测算（综合版）
    
    综合年柱、日柱、时柱，提供完整的本命五行分析。
    数据来源:
    - 纳音五行: 《五行大义》卷一（隋·萧吉）
    - 生肖五行: 《论衡·物势》（汉·王充）
    - 日主五行: 《渊海子平》、《三命通会》
    - 时柱五行: 《五鼠遁诀》（《遁甲符应经》）
    
    Args:
        year: 公历年份
        month: 公历月（可选，不提供则不计算日柱）
        day: 公历日（可选，不提供则不计算日柱）
        hour: 出生时辰（24小时制，默认12）
        
    Returns:
        完整的五行测算结果字典
    """
    nayin_result = get_nayin_wuxing(year)
    shengxiao_result = get_shengxiao_wuxing(year)
    
    # 本命五行取纳音五行（命理以纳音为尊）
    benming_wuxing = nayin_result["nayin_wuxing"]
    
    # 如果有完整的日期，计算日柱和时柱
    result = {**nayin_result, **shengxiao_result}
    
    if month > 0 and day > 0:
        day_gan, day_dz = get_gan_zhi_day(year, month, day)
        day_wuxing = TIAN_GAN_WU_XING.get(day_gan, "未知")
        
        # 计算月柱（基于节气）
        month_gan_zhi = get_gan_zhi_month(year, month, day)
        month_wuxing = TIAN_GAN_WU_XING.get(month_gan_zhi[0], "未知")
        
        result["day_gan"] = day_gan
        result["day_dz"] = day_dz
        result["day_gan_zhi"] = f"{day_gan}{day_dz}"
        result["day_wuxing"] = day_wuxing  # 日主五行（日元）
        result["month_gan_zhi"] = month_gan_zhi
        result["month_wuxing"] = month_wuxing
        result["is_rizhu"] = True
        
        # 如果有时辰，计算时柱
        if 0 <= hour <= 23:
            hour_gan, hour_dz = get_gan_zhi_hour(day_gan, year, month, day, hour)
            hour_wuxing = TIAN_GAN_WU_XING.get(hour_gan, "未知")
            
            result["hour_gan"] = hour_gan
            result["hour_dz"] = hour_dz
            result["hour_gan_zhi"] = f"{hour_gan}{hour_dz}"
            result["hour_wuxing"] = hour_wuxing
            result["shichen"] = SHI_CHEN_NAMES.get(hour_dz, f"{hour_dz}时 ({hour:02d}:00-{hour+2:02d}:00)")
            
            # 四柱完整信息
            result["four_pillars"] = {
                "year": f"{nayin_result['tian_gan']}{nayin_result['di_zhi']}",
                "month": month_gan_zhi,
                "day": f"{day_gan}{day_dz}",
                "hour": f"{hour_gan}{hour_dz}",
            }
    
    return {
        **result,
        "benming_wuxing": benming_wuxing,  # 本命五行（纳音）
        "description": _get_wuxing_description(benming_wuxing, nayin_result["nayin_name"]),
    }


